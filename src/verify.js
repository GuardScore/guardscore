// verify(change): the primitive agents call before shipping a change.
// Milestone 1: the quick check is not built yet, so every change escalates to
// the deep check. The response format is final; tier and reason say so.
import { readFileSync, existsSync } from 'node:fs';
import { join, basename } from 'node:path';
import { buildDb, discardEngine } from './db.js';
import { introspect } from './introspect.js';
import { autoFixtures } from './fixtures.js';
import { runAdvisor } from './advisor.js';
import { secretResults } from './secrets.js';
import { configChecks } from './config.js';
import { serverCodeChecks } from './servercode.js';
import { gauntlet, summarize } from './gauntlet.js';
import { buildFixes, makeRecursionFix } from './fixes.js';
import { issueReceipt, sha256 } from './receipts.js';

export const FORMAT_VERSION = 'verified-change/0.1';

export function loadApp(dir) {
  const read = f => (existsSync(join(dir, f)) ? readFileSync(join(dir, f), 'utf8') : '');
  const manifest = existsSync(join(dir, 'manifest.json')) ? JSON.parse(read('manifest.json')) : {};
  return { name: manifest.name || basename(dir), dir, sourceDir: dir, manifest, migration: read('migration.sql'), seed: read('seed.sql') };
}

// Very large apps can exhaust the shared engine's stack ("stack depth limit
// exceeded") after many checks in one process. That is the engine's limit, not
// the app's: throw the engine away and redo the check on a fresh one.
async function run(app, after = [], opts = {}) {
  try { return await runOnce(app, after, opts); }
  catch (e) {
    if (!/stack depth limit exceeded/i.test(String(e?.message))) throw e;
    await discardEngine();
    const prev = process.env.VC_FRESH_DB;
    process.env.VC_FRESH_DB = '1';
    try { return await runOnce(app, after, opts); } finally { if (prev === undefined) delete process.env.VC_FRESH_DB; else process.env.VC_FRESH_DB = prev; }
  }
}

async function runOnce(app, after = [], opts = {}) {
  const db = await buildDb({ migrations: [app.migration], seed: app.seed, after });
  try {
    const fixtures = await autoFixtures(db, app.manifest);
    const schema = await introspect(db, app.manifest);
    // A table with row level security on and no policies is either a lock-out
    // bug or a server-only table (Stripe customer ids). Only the author's own
    // comment next to it tells them apart; with one, users aren't expected in.
    const sqlText = [app.migration, ...after].join('\n');
    // Migrations generated by an ORM (Drizzle's statement-breakpoint marker,
    // Prisma's headers) mean the app talks to the database from its server;
    // a table it locked with no policies is kept from the public API on purpose.
    const ormManaged = /--> statement-breakpoint|^-- CreateTable$/m.test(sqlText);
    // Every table locked with row level security and no policy at all: the
    // whole app goes through its own server, by design.
    const allLocked = schema.length > 1 && schema.every(t => t.rls && !(t.policies || []).length);
    for (const t of schema) {
      if (t.policies.length || t.legitOpsFromManifest) continue;
      if ((ormManaged || allLocked) && t.rls) { t.legitOps = []; t.serverOnly = true; continue; }
      // Mirrors of Stripe and other integrations, webhook and audit logs, job
      // queues: filled by the server, never by the user's browser.
      if (t.rls && /(^|_)(stripe|billing|webhooks?|audit|logs?|events?|analytics|cron|jobs?|queues?|sync|integrations?|telemetry|outbox)(_|$)/i.test(t.name)) { t.legitOps = []; t.serverOnly = true; continue; }
      const name = t.name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      const at = sqlText.search(new RegExp(`create\\s+table\\s+(if\\s+not\\s+exists\\s+)?(public\\.)?"?${name}"?\\s*\\(`, 'i'));
      const near = at < 0 ? '' : sqlText.slice(Math.max(0, at - 400), at + 2500);
      const rls = sqlText.match(new RegExp(`--[^\\n]*\\n?[^\\n]*alter\\s+table\\s+(public\\.)?"?${name}"?\\s+enable\\s+row\\s+level\\s+security[^\\n]*\\n(\\s*--[^\\n]*\\n)*`, 'i'))?.[0] || '';
      const comments = (near + '\n' + rls).split('\n').filter(l => /--|\/\*|\*/.test(l)).join(' ');
      if (/\b(private|internal|server[- ]only|service[_ ]role|not (be )?accessible (to|by) users|must not have access|webhook|backend only)\b/i.test(comments)) { t.legitOps = []; t.serverOnly = true; }
    }
    for (const t of schema) {
      if (fixtures.privilegeProbes?.[t.name]) t.privilegeProbe = fixtures.privilegeProbes[t.name];
      if (fixtures.shareTables?.includes(t.name)) t.shareTable = true;
    }
    const results = await gauntlet(db, schema, undefined, { only: opts.only });
    const advisor = await runAdvisor(db);
    // Keys in the app's own files: a service-role key in the browser undoes RLS.
    let secretWarnings = [];
    if (app.sourceDir) {
      const s = secretResults(app.sourceDir);
      results.push(...s.results);
      secretWarnings = s.warnings;
    }
    const settings = app.sourceDir ? [...configChecks(app.sourceDir), ...serverCodeChecks(app.sourceDir)] : [];
    // Creating a row fails because the app's own trigger writes another table
    // against that table's rules (a creator added as 'admin' after 'admin' was
    // dropped from the allowed roles): every real user hits this, so it breaks
    // the app rather than leaving a gap.
    for (const f of fixtures.failed.filter(x => x.side === 'A')) {
      const m = String(f.error).match(/new row for relation "([^"]+)" violates check constraint "([^"]+)"/);
      if (!m || m[1] === f.table || results.some(x => x.id === `${f.table}.legit.create`)) continue;
      results.push({ id: `${f.table}.legit.create`, table: f.table, class: 'legit', kind: 'legit', status: 'broken',
        proof: { actor: 'user A (the owner)', sql: `insert into public."${f.table}" ...`, observed: { error: f.error },
          note: `creating a row in "${f.table}" runs a trigger that writes "${m[1]}" with a value its rule "${m[2]}" rejects, so it fails for every user` } });
    }
    // Server-only functions that the API can still run. The migration says
    // who should run it (revoked from PUBLIC, granted to service_role); the
    // database's own privilege table says who can. A mismatch is the proof.
    const definers = (await db.query(`select p.proname as name, p.oid::regprocedure::text as sig,
        has_function_privilege('anon', p.oid, 'EXECUTE') as anon_can, has_function_privilege('authenticated', p.oid, 'EXECUTE') as auth_can, p.prosrc as src
      from pg_proc p join pg_namespace n on n.oid = p.pronamespace
      where n.nspname = 'public' and p.prosecdef and p.prokind = 'f' and p.prosrc ~* '\\m(update|delete|insert|truncate)\\M'
        and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')`)).rows;
    for (const f of definers) {
      const esc = f.name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      const revokedFrom = role => new RegExp(`revoke\\s+(all|execute)[^;]*on\\s+function\\s+(public\\.)?"?${esc}"?\\s*\\([^;]*from\\s+[^;]*\\b${role}\\b`, 'i').test(sqlText);
      const grantedToServiceOnly = new RegExp(`grant\\s+(all|execute)[^;]*on\\s+function\\s+(public\\.)?"?${esc}"?\\s*\\([^;]*to\\s+service_role\\s*;`, 'i').test(sqlText);
      const meantServerOnly = revokedFrom('public') || grantedToServiceOnly;
      const explicitToApi = new RegExp(`grant\\s+(all|execute)[^;]*on\\s+function\\s+(public\\.)?"?${esc}"?\\s*\\([^;]*to\\s+[^;]*\\b(anon|authenticated)\\b`, 'i').test(sqlText);
      if (!meantServerOnly || explicitToApi) continue;
      // The function turns away everyone but the server itself (raise unless
      // auth.role() is service_role): callable, but harmless.
      if (/raise/i.test(f.src || '') && /'service_role'/.test(f.src || '') && /auth\.role\(\)|request\.jwt\.claim|current_user|session_user/i.test(f.src || '')) continue;
      for (const [role, can, actor] of [['anon', f.anon_can, 'anonymous visitor'], ['authenticated', f.auth_can, 'any signed-in user']]) {
        // Revoking only from public/anon and leaving authenticated able to run it
        // is the normal "logged-in users only" pattern, not "server only": a
        // finding for authenticated needs the migration to lock authenticated out too.
        if (role === 'authenticated' && !revokedFrom('authenticated') && !grantedToServiceOnly) continue;
        results.push({ id: `${f.name}.definer_exposed.${role}`, table: f.name, class: 'definer_exposed', kind: 'attack', status: can ? 'leaked' : 'blocked',
          proof: { actor, role, sql: `select has_function_privilege('${role}', '${f.sig.replace(/'/g, "''")}', 'EXECUTE')`, observed: { can_execute: !!can },
            note: `the migration limits ${f.sig} to the server, but ${role} can still execute it` } });
      }
    }
    // Policies that call a helper function signed-in users may not execute
    // ("permission denied for function member_ids"): the app closed that path
    // to the API on purpose, so a real user failing there isn't a broken app.
    const lockedFns = new Set((await db.query(`select p.proname as n from pg_proc p join pg_namespace n on n.oid = p.pronamespace
      where n.nspname = 'public' and not has_function_privilege('authenticated', p.oid, 'EXECUTE')`)).rows.map(r => r.n));
    for (let i = results.length - 1; i >= 0; i--) {
      const r = results[i];
      const fn = String(r.proof?.observed?.error || '').match(/permission denied for function (\w+)/)?.[1];
      if (r.kind === 'legit' && r.status === 'broken' && fn && lockedFns.has(fn)) results.splice(i, 1);
    }
    // The same for tables: "permission denied for table X" where the app never
    // granted (or revoked) that command on X for signed-in users. The app does
    // that write through its own functions, so the direct path failing is by
    // design. auth.users stays: a policy reading it breaks every query.
    const closedTables = new Set((await db.query(`select c.relname as n from pg_class c join pg_namespace n on n.oid = c.relnamespace
      where n.nspname in ('public', 'storage') and c.relkind in ('r', 'p', 'v')
        and not (has_table_privilege('authenticated', c.oid, 'SELECT') and has_table_privilege('authenticated', c.oid, 'INSERT')
             and has_table_privilege('authenticated', c.oid, 'UPDATE') and has_table_privilege('authenticated', c.oid, 'DELETE'))`)).rows.map(r => r.n));
    for (let i = results.length - 1; i >= 0; i--) {
      const r = results[i];
      const tb = String(r.proof?.observed?.error || '').match(/permission denied for table (\w+)/)?.[1];
      if (r.kind === 'legit' && r.status === 'broken' && tb && tb !== 'users' && closedTables.has(tb)) results.splice(i, 1);
    }
    // Writes that the app performs only through its own security-definer
    // functions (record_attempt(), enroll()): the table has no INSERT/UPDATE
    // policy for signed-in users, and a definer function inserts or updates it.
    // A direct write from a user failing (an RLS violation) is then by design,
    // not a broken app.
    const defWriters = (await db.query(`select lower(p.prosrc) as src from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.prosecdef`)).rows.map(r => r.src).join('\n');
    const writeGuarded = new Set();
    for (const t of schema) {
      const hasIns = (t.policies || []).some(pp => /INSERT|ALL/i.test(pp.cmd || 'ALL'));
      const hasUpd = (t.policies || []).some(pp => /UPDATE|ALL/i.test(pp.cmd || 'ALL'));
      const esc = t.name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      const written = new RegExp(`\\b(insert\\s+into|update)\\s+(public\\.)?"?${esc}"?\\b`, 'i').test(defWriters);
      if (written && (!hasIns || !hasUpd)) writeGuarded.add(t.name);
    }
    for (let i = results.length - 1; i >= 0; i--) {
      const r = results[i];
      if (r.kind === 'legit' && r.status === 'broken' && /\.legit\.(insert_own|update_own|create|new_user_row)\b/.test(r.id)
        && /row-level security|violates row-level/i.test(r.proof?.observed?.error || '') && writeGuarded.has(r.table)) results.splice(i, 1);
    }
    // A legit insert whose policy requires a parent to be in a certain state
    // (WITH CHECK ... EXISTS(select ... where ... published/active)): our sample
    // parent may not be in that state, so the failure is our fixture's, not the
    // app's. Report it as inconclusive rather than a broken app.
    for (const r of results) {
      if (r.kind !== 'legit' || r.status !== 'broken' || !/\.legit\.(insert_own|create|new_user_row)\b/.test(r.id)) continue;
      if (!/row-level security|violates row-level/i.test(r.proof?.observed?.error || '')) continue;
      const t = schema.find(x => x.name === r.table);
      const insPol = (t?.policies || []).filter(pp => /INSERT|ALL/i.test(pp.cmd || 'ALL')).map(pp => pp.text).join(' ');
      if (/exists\s*\(/i.test(insPol) && /\b(published|is_public|public|active|is_active|approved|status|visibility)\b/i.test(insPol)) {
        r.status = 'inconclusive';
        r.proof.note = 'the verifier could not confirm this: the insert needs a parent row in a particular state (e.g. a published course) that the sample data did not set up. Check it by hand.';
      }
    }
    // Every rule on the table goes through such a function: no user reaches it.
    for (const t of schema) {
      const pols = t.policies || [];
      if (pols.length && pols.every(p => [...lockedFns].some(f => new RegExp(`\\b${f}\\s*\\(`).test(p.text)))) t.noApiAccess = true;
    }
    // A table nobody outside the server can reach needs no sample rows: there
    // is no attack to run on it, so it isn't a gap in the check.
    for (let i = results.length - 1; i >= 0; i--) {
      const r = results[i];
      if (r.kind === 'coverage' && schema.find(t => t.name === r.table)?.noApiAccess) results.splice(i, 1);
    }
    // Say why a table couldn't be tested: the error from making its sample rows.
    for (const r of results.filter(x => x.kind === 'coverage')) {
      const f = fixtures.failed.find(x => x.table === r.table);
      if (f) r.proof.reason = `the verifier's own sample rows for it were rejected (${f.error}); usually a trigger or check the sample data didn't satisfy. Don't add test data to your migrations for this`;
      else if (fixtures.skipped.includes(r.table)) r.proof.reason = 'left empty on purpose (share links, invitations and staff tables grant access by design)';
    }
    return { schema, results, summary: { ...summarize(results, { skipped: fixtures.skipped }), advisor, secretWarnings, settings, fixtures: { filled: fixtures.filled, failed: fixtures.failed, skipped: fixtures.skipped } } };
  } finally {
    await db.close();
  }
}

// Proven fixes: apply the suggested database fixes to the private copy and run
// the whole check again. A fix is "proven" only if every finding it targets is
// now blocked, real users still work on that table, and nothing new leaks.
// Fixes that aren't database changes (moving a key out of the browser) are
// labelled as such; anything else that doesn't pass says what still fails.
async function proveFixes(app, after, fixes, beforeResults) {
  const db = fixes.filter(f => f.kind !== 'code');
  for (const f of fixes.filter(f => f.kind === 'code')) f.proof = { status: 'code_change', note: 'not a database change; re-run the check after making it' };
  if (!db.length) return null;
  const attempt = async list => {
    try { return await run({ ...app, sourceDir: null }, [...after, list.map(f => f.sql).join('\n')]); }
    catch (e) { return { error: e.message }; }
  };
  const judge = (f, res, before) => {
    if (res.error) return { status: 'unproven', note: `the fix SQL failed to apply: ${res.error}` };
    const byId = new Map(res.results.map(r => [r.id, r]));
    const still = f.findings.filter(id => byId.get(id) && byId.get(id).status !== 'blocked' && byId.get(id).status !== 'ok');
    const broken = res.results.filter(r => r.kind === 'legit' && r.status === 'broken' && r.table === f.table);
    // Access someone had before the fix and lost (staff reading orders, say).
    const beforeById = new Map(before.map(r => [r.id, r]));
    const lost = res.results.filter(r => r.kind === 'legit' && /\.legit\.(staff_read|staff_update\.|view_shared)/.test(r.id) && r.status === 'ok' && r.proof?.observed?.rows_visible === 0
      && beforeById.get(r.id)?.status === 'ok' && beforeById.get(r.id)?.proof?.observed?.rows_visible > 0);
    broken.push(...lost);
    const beforeLeaks = new Set(before.filter(r => r.status === 'leaked').map(r => r.id));
    // An attack that only "failed" before because every query errored with
    // infinite recursion was never really blocked: fixing the recursion reveals
    // that hole, it doesn't open it. Those are reported, not held against the fix.
    const masked = new Set(before.filter(r => /infinite recursion/i.test(r.proof?.observed?.error || '')).map(r => r.id));
    const opened = res.results.filter(r => r.status === 'leaked' && !beforeLeaks.has(r.id) && r.class !== 'service_key_exposed');
    const newLeaks = opened.filter(r => !masked.has(r.id));
    const revealed = opened.filter(r => masked.has(r.id));
    if (!still.length && !broken.length && !newLeaks.length) {
      const fixed = f.findings.filter(id => byId.has(id)).length;
      return { status: 'proven', note: `applied to the private copy and re-checked: ${fixed} finding(s) now blocked, real users on "${f.table}" still work, nothing new leaks`
        + (revealed.length ? `; with the recursion gone, the check can now reach ${revealed.map(r => r.id).join(', ')}, which leak and need their own fix (run the check again)` : '') };
    }
    const why = [still.length && `still failing: ${still.join(', ')}`, broken.length && `blocks real users: ${broken.map(b => b.id).join(', ')}`, newLeaks.length && `opens: ${newLeaks.map(b => b.id).join(', ')}`].filter(Boolean);
    return { status: 'unproven', note: `applied to the private copy and re-checked; ${why.join('; ')}` };
  };
  const base = { results: beforeResults };
  let all = await attempt(db);
  // Fixing one infinite recursion can uncover another behind it (a second loop
  // the first error hid). Add a fix for each newly surfaced loop and try again.
  for (let round = 0; round < 3 && !all.error; round++) {
    const loops = new Map();
    for (const r of all.results) {
      const m = (r.proof?.observed?.error || '').match(/infinite recursion detected in policy for relation "([^"]+)"/i);
      if (m && !fixes.some(f => f.loopTable === m[1])) {
        if (!loops.has(m[1])) loops.set(m[1], []);
        if (r.status === 'broken') loops.get(m[1]).push(r.id);
      }
    }
    // A table fix can also expose a hole elsewhere, typically a view over the
    // now-private table that skips its row level security. Fix those too.
    const beforeLeaks = new Set(beforeResults.filter(r => r.status === 'leaked').map(r => r.id));
    // Holes a recursion error hid (the attack "failed" only because every query
    // errored) are fixed the same way once the loop is gone.
    const masked = new Set(beforeResults.filter(r => /infinite recursion/i.test(r.proof?.observed?.error || '')).map(r => r.id));
    const knock = all.results.filter(r => ((r.status === 'leaked' && !beforeLeaks.has(r.id)
        && (r.class === 'view_bypass' || masked.has(r.id) || fixes.some(f => f.surfaced && f.loopTable === r.table)))
      // A real-user check that only errored with the loop before, and now fails
      // for its own reason (a team creator who can't join their team).
      || (r.kind === 'legit' && r.status === 'broken' && masked.has(r.id) && !/infinite recursion/i.test(r.proof?.observed?.error || '')))
      && !fixes.some(f => f.table === r.table && !f.loopTable));
    if (!loops.size && !knock.length) break;
    const extra = [...[...loops].map(([L, ids]) => makeRecursionFix(L, ids)), ...buildFixes(all.schema, knock)];
    for (const f of extra) { f.surfaced = true; fixes.push(f); db.push(f); }
    // The earlier fixes' findings that were stuck behind the new loop count toward it.
    all = await attempt(db);
  }
  for (const f of db) {
    f.proof = judge(f, all, base.results);
    if (f.surfaced) f.proof.note = `found while proving the other fixes (a problem they uncovered); ${f.proof.note}`;
  }
  // If the fixes together didn't hold (one bad fix can break the others), try
  // the rest one at a time so a good fix isn't labelled unproven because of it.
  if (db.some(f => f.proof.status !== 'proven') && db.length > 1) {
    for (const f of db.filter(x => x.proof.status !== 'proven')) {
      const alone = await attempt([f]);
      const p = judge(f, alone, base.results);
      if (p.status === 'proven') f.proof = { ...p, note: `${p.note} (when applied on its own)` };
    }
  }
  const verdictAfter = all.error ? 'invalid_fix' : all.summary.verdict;
  return { verdictAfterAllFixes: verdictAfter, proven: db.filter(f => f.proof.status === 'proven').length, total: db.length };
}

/** Deep-check an app as it is. */
export async function checkApp(app, { logDir, only } = {}) {
  const r = await run(app, [], { only });
  const fixes = buildFixes(r.schema, r.results);
  const t0 = Date.now(); const fixCheck = await proveFixes(app, [], fixes, r.results); if (process.env.VC_TIME) console.error(`proveFixes ${Date.now() - t0}ms`);
  const out = {
    format: FORMAT_VERSION,
    app: app.name,
    tier: 'deep',
    ...r.summary,
    findings: r.results.filter(x => x.status === 'leaked' || x.status === 'broken'),
    inconclusiveChecks: r.results.filter(x => x.status === 'inconclusive'),
    fixes,
    fixCheck,
    declarations: app.manifest.declarations || [],
    checks: r.results,
  };
  if (logDir) out.receipt = receipt(logDir, { kind: 'check', app: app.name, change: null, out, manifest: app.manifest });
  return out;
}

/**
 * Verify a change against an app: run the gauntlet before and after the change
 * and report the verdict after, plus any regressions the change introduced.
 */
export async function verify(app, changeSql, { logDir } = {}) {
  const before = await run(app);
  let after;
  try {
    after = await run(app, [changeSql]);
  } catch (e) {
    return { format: FORMAT_VERSION, app: app.name, tier: 'deep', verdict: 'invalid_change', error: e.message };
  }
  const beforeStatus = new Map(before.results.map(r => [r.id, r.status]));
  // A regression is anything leaking or broken after the change that wasn't
  // before, including checks that only exist because of the change (a new
  // policy that starts trusting a role column users can edit).
  const regressions = after.results.filter(r =>
    (r.status === 'leaked' && beforeStatus.get(r.id) !== 'leaked') ||
    (r.status === 'broken' && beforeStatus.get(r.id) !== 'broken'));
  const fixed = before.results.filter(r =>
    r.status === 'leaked' && after.results.find(a => a.id === r.id)?.status === 'blocked');

  const afterFixes = buildFixes(after.schema, after.results);
  const out = {
    format: FORMAT_VERSION,
    app: app.name,
    tier: 'deep',
    escalated: true,
    reason: 'quick check not enabled in milestone 1; every change runs the deep check',
    ...after.summary,
    guardScoreBefore: before.summary.guardScore,
    regressions,
    fixedByChange: fixed.map(r => r.id),
    findings: after.results.filter(x => x.status === 'leaked' || x.status === 'broken'),
    inconclusiveChecks: after.results.filter(x => x.status === 'inconclusive'),
    fixes: afterFixes,
    fixCheck: await proveFixes(app, [changeSql], afterFixes, after.results),
    declarations: app.manifest.declarations || [],
    checks: after.results,
  };
  if (logDir) out.receipt = receipt(logDir, { kind: 'verify', app: app.name, change: changeSql, out, manifest: app.manifest });
  return out;
}

function receipt(logDir, { kind, app, change, out, manifest = {} }) {
  return issueReceipt({
    logDir,
    body: {
      format: FORMAT_VERSION,
      kind,
      app,
      time: new Date().toISOString(),
      change_sha256: change ? sha256(change) : null,
      verdict: out.verdict,
      guard_score: out.guardScore,
      results_sha256: sha256(JSON.stringify(out.checks.map(c => [c.id, c.status]))),
      // What the builder said is meant to be open: part of what was certified.
      declared_public: manifest.publicTables || [],
      declared_shared: manifest.sharedTables || [],
      // Each declaration with its reason and any flags, including ignored ones.
      declarations: (manifest.declarations || []).map(d => ({ table: d.table, scope: d.scope, reason: d.reason, honoured: d.honoured, flags: d.flags })),
    },
  });
}
