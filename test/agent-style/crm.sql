-- Agent-style CRM: enums, money, dates, arrays, jsonb, updated_at triggers, a view, storage bucket.
create extension if not exists "pgcrypto";
create type public.invoice_status as enum ('draft', 'sent', 'paid', 'overdue');
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text, business_name text, avatar_url text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table public.clients (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  name text not null, email text, phone text, company text, notes text,
  tags text[] not null default '{}',
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table public.projects (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  client_id uuid not null references public.clients(id) on delete cascade,
  name text not null, status text not null default 'active' check (status in ('active', 'completed', 'on_hold')),
  hourly_rate numeric(10,2), start_date date, due_date date,
  created_at timestamptz not null default now()
);
create table public.invoices (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  client_id uuid not null references public.clients(id),
  project_id uuid references public.projects(id) on delete set null,
  invoice_number text not null, status public.invoice_status not null default 'draft',
  issue_date date not null default current_date, due_date date not null,
  line_items jsonb not null default '[]'::jsonb, total numeric(12,2) not null default 0,
  unique (user_id, invoice_number)
);
create table public.invoice_items (
  id bigint generated by default as identity primary key,
  invoice_id uuid not null references public.invoices(id) on delete cascade,
  description text not null, quantity numeric not null default 1, unit_price numeric(12,2) not null
);
create index on public.clients (user_id);
create or replace function public.set_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;
create trigger clients_updated before update on public.clients for each row execute function public.set_updated_at();
create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path = '' as $$
begin insert into public.profiles (id, full_name) values (new.id, new.raw_user_meta_data->>'full_name'); return new; end $$;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();
alter table public.profiles enable row level security;
alter table public.clients enable row level security;
alter table public.projects enable row level security;
alter table public.invoices enable row level security;
alter table public.invoice_items enable row level security;
create policy "Users can view own profile" on public.profiles for select using ((select auth.uid()) = id);
create policy "Users can update own profile" on public.profiles for update using ((select auth.uid()) = id);
create policy "Users manage own clients" on public.clients for all using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "Users manage own projects" on public.projects for all using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "Users manage own invoices" on public.invoices for all using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
-- Classic slip: items are checked only for being logged in.
create policy "Authenticated users manage items" on public.invoice_items for all to authenticated using (true) with check (true);
create view public.invoice_totals with (security_invoker = true) as
  select i.id, i.user_id, sum(ii.quantity * ii.unit_price) as total from public.invoices i left join public.invoice_items ii on ii.invoice_id = i.id group by i.id;
insert into storage.buckets (id, name, public) values ('avatars', 'avatars', true) on conflict do nothing;
alter publication supabase_realtime add table public.invoices;
